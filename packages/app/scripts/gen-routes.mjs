// Writes src/api/routes.gen.ts: every src/api/**/route.ts with its URL pattern.
// Run after adding or removing a route file: pnpm --filter @labebal/app gen:routes
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const apiDir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "api");
const found = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name === "route.ts") found.push(path.relative(apiDir, path.dirname(p)).split(path.sep).filter(Boolean));
  }
})(apiDir);

// Static segments before parameters at each position, so /counters/reserve wins over /counters/[id].
const rank = (seg) => (seg.startsWith("[") ? 1 : 0);
found.sort((a, b) => {
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    if (a[i] === undefined) return -1;
    if (b[i] === undefined) return 1;
    const r = rank(a[i]) - rank(b[i]);
    if (r) return r;
    if (a[i] !== b[i]) return a[i] < b[i] ? -1 : 1;
  }
  return 0;
});

const lines = [
  "// Generated by scripts/gen-routes.mjs. Do not edit.",
  'import type { RouteModule } from "./http";',
  ...found.map((segs, i) => `import * as r${i} from "./${[...segs, "route"].join("/")}";`),
  "",
  "/** [pattern segments, module]; parameters are \"[name]\". Static segments sort first. */",
  "export const ROUTES: [string[], RouteModule][] = [",
  ...found.map((segs, i) => `  [${JSON.stringify(segs)}, r${i} as RouteModule],`),
  "];",
  "",
];
fs.writeFileSync(path.join(apiDir, "routes.gen.ts"), lines.join("\n"));
console.log(`${found.length} routes`);
