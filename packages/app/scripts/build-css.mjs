// Builds styles/labebal.css: Tailwind compiled from styles/prebuilt.src.css,
// then every rule scoped to `.labebal` so the stylesheet can sit on any page.
//
//   :root, :host, html, body     -> .labebal
//   *, ::before, ::after, h1 ... -> :where(.labebal) X   (plus .labebal itself for *)
//   .flex, .dark\:x:is(.dark *)  -> :where(.labebal) .flex ...
//
// :where() adds no specificity, so the utilities keep their usual order.
// Rules that already mention .labebal (the colour tokens), @keyframes and
// @property are left alone.
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwind from "@tailwindcss/postcss";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const from = path.join(root, "styles", "prebuilt.src.css");
const to = path.join(root, "styles", "labebal.css");
const SCOPE = ":where(.labebal)";

function scopeSelector(sel) {
  const s = sel.trim();
  if (!s || s.includes(".labebal")) return [s];
  if (/^(:root|:host|html|body)$/.test(s)) return [".labebal"];
  // ":root, :host" style compound lists are split by postcss already.
  if (/^(html|body|:root|:host)\b/.test(s)) return [s.replace(/^(html|body|:root|:host)/, ".labebal")];
  if (s === "*" || s.startsWith("*")) return [`.labebal${s.slice(1)}`, `${SCOPE} ${s}`];
  return [`${SCOPE} ${s}`];
}

const scope = () => ({
  postcssPlugin: "labebal-scope",
  Rule(rule) {
    if (rule.__scoped) return;
    let p = rule.parent;
    while (p) {
      if (p.type === "atrule" && /keyframes$/i.test(p.name)) return;
      p = p.parent;
    }
    // Nested rules (&:hover, ...) are scoped through their parent.
    if (rule.parent?.type === "rule") return;
    rule.selectors = rule.selectors.flatMap(scopeSelector);
    rule.__scoped = true;
  },
});
scope.postcss = true;

const css = await fs.readFile(from, "utf8");
const out = await postcss([tailwind({ base: root, optimize: { minify: true } }), scope()]).process(css, { from, to });
await fs.writeFile(to, `/* labebal prebuilt styles (generated by scripts/build-css.mjs; scoped to .labebal) */\n${out.css}`);
const kb = (Buffer.byteLength(out.css) / 1024).toFixed(0);
console.log(`styles/labebal.css: ${kb} KB`);
